function elevationShadows(
  mood: SurfaceMood,
  level: ElevationMood,
  ink: string
): Pick<ThemeChrome, "shadowSm" | "shadowMd" | "shadowLg" | "cardHoverShadow" | "buttonShadow"> {
  const rgb =
    mood === "dark" ? "0, 0, 0" : hexToRgb(ink) || "5, 23, 65";
  switch (level) {
    case "flat":
      return {
        shadowSm: "none",
        shadowMd: `0 4px 12px rgba(${rgb}, 0.06)`,
        shadowLg: `0 8px 20px rgba(${rgb}, 0.08)`,
        cardHoverShadow: `0 8px 18px rgba(${rgb}, 0.1)`,
        buttonShadow: "none",
      };
    case "deep":
      return {
        shadowSm: `0 8px 18px -10px rgba(${rgb}, 0.28)`,
        shadowMd: `0 16px 36px rgba(${rgb}, 0.28)`,
        shadowLg: `0 28px 56px -16px rgba(${rgb}, 0.42)`,
        cardHoverShadow: `0 24px 48px -16px rgba(${rgb}, 0.36)`,
        buttonShadow: `0 14px 28px -10px rgba(${rgb}, 0.35)`,
      };
    case "soft":
      return {
        shadowSm: `0 6px 14px -10px rgba(${rgb}, 0.18)`,
        shadowMd: `0 10px 28px rgba(${rgb}, 0.18)`,
        shadowLg: `0 18px 40px -18px rgba(${rgb}, 0.38)`,
        cardHoverShadow: `0 18px 40px -18px rgba(${rgb}, 0.28)`,
        buttonShadow: `0 10px 22px -12px rgba(${rgb}, 0.28)`,
      };
    default: {
      const _never: never = level;
      return _never;
    }
  }
}

function hexToRgb(hex: string): string | null {
  const raw = hex.trim().replace("#", "");
  const full =
    raw.length === 3
      ? raw
          .split("")
          .map((c) => c + c)
          .join("")
      : raw.slice(0, 6);
  if (!/^[0-9a-fA-F]{6}$/.test(full)) return null;
  const r = parseInt(full.slice(0, 2), 16);
  const g = parseInt(full.slice(2, 4), 16);
  const b = parseInt(full.slice(4, 6), 16);
  return `${r}, ${g}, ${b}`;
}

function seedToPreset(seed: ThemeSeed): ThemePreset {
  const radius = RADIUS[seed.radius];
  const shadows = elevationShadows(seed.mood, seed.elevation, seed.ink);
  const chrome: ThemeChrome = {
    pageBg: seed.paper,
    sectionBg: seed.mist,
    cardBg: seed.snow,
    headerBg: seed.ink,
    footerBg: seed.ink,
    overlayBg: seed.overlay,
    textHeading: seed.heading,
    textBody: seed.body,
    textMuted: seed.muted,
    textInverse: seed.inverse,
    textLink: seed.link,
    primary: seed.accent,
    secondary: seed.secondary,
    success: seed.success,
    buttonBg: seed.accent,
    buttonText: seed.accentInk,
    buttonBorder: "transparent",
    buttonHoverBg: seed.accentDeep,
    buttonHoverText: seed.accentInk,
    buttonActiveBg: seed.accentDeep,
    buttonDisabledBg: seed.mood === "dark" ? "#334155" : "#94a3b8",
    buttonDisabledText: seed.mood === "dark" ? "#94a3b8" : "#f8fafc",
    buttonRadius: radius.buttonRadius,
    buttonShadow: shadows.buttonShadow,
    cardHoverBg: seed.snow,
    cardHoverShadow: shadows.cardHoverShadow,
    navHover: seed.navHover,
    chipHover: seed.mood === "dark" ? "rgba(255,255,255,0.08)" : "rgba(15,23,42,0.06)",
    borderColor: seed.border,
    borderWidth: "1px",
    radiusSm: radius.radiusSm,
    radiusMd: radius.radiusMd,
    radiusLg: radius.radiusLg,
    radiusXl: radius.radiusXl,
    radiusCard: radius.radiusCard,
    radiusInput: radius.radiusInput,
    headerGlass: seed.headerGlass,
    cardGlass: seed.cardGlass,
    searchGlass: seed.searchGlass,
    focusRing: seed.accent,
    shadowSm: shadows.shadowSm,
    shadowMd: shadows.shadowMd,
    shadowLg: shadows.shadowLg,
    inputBg: seed.inputBg,
    inputText: seed.inputText,
    inputBorder: seed.border,
    inputPlaceholder: seed.inputPlaceholder,
    tabActiveBg: seed.accent,
    tabActiveText: seed.accentInk,
    tabIdleBg: "transparent",
    tabIdleText: seed.tabIdleText,
    badgeBg: seed.badgeBg,
    badgeText: seed.badgeText,
    iconChrome: seed.icon,
  };

  return {
    id: seed.id,
    nameAr: seed.nameAr,
    nameEn: seed.nameEn,
    nameTr: seed.nameTr,
    descriptionAr: seed.descriptionAr,
    descriptionEn: seed.descriptionEn,
    descriptionTr: seed.descriptionTr,
    theme: {
      colors: colorsFromChrome(chrome),
      radius: radiusFromChrome(chrome),
      border: borderFromChrome(chrome),
      image: { treatment: seed.image, radius: chrome.radiusCard },
      arabicFontId: seed.arabicFontId,
      latinFontId: seed.latinFontId,
      chrome,
    },
  };
}

