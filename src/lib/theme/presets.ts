export const THEME_PRESETS: ThemePreset[] = SEEDS.map(seedToPreset);

const LEGACY_PRESET_ALIASES: Record<string, string> = {
  "emerald-coast": FACTORY_PRESET_ID,
  "midnight-gold": "luxury-navy",
  mediterranean: "mediterranean-teal",
  "desert-rose": "sunset-coral",
  "arctic-graphite": "corporate-slate",
  "royal-sapphire": "royal-purple",
};

export function getThemePreset(id: string): ThemePreset | undefined {
  const resolved = LEGACY_PRESET_ALIASES[id] || id;
  return THEME_PRESETS.find((preset) => preset.id === resolved);
}

export function factoryPreset(): ThemePreset {
  return THEME_PRESETS[0]!;
}
