export function catalogByCode(): Map<string, CatalogCurrency> {
  return new Map(CURRENCY_CATALOG.map((row) => [row.code, row]));
}

export function findCatalogCurrency(code: string): CatalogCurrency | undefined {
  const wanted = code.trim().toUpperCase();
  return CURRENCY_CATALOG.find((row) => row.code === wanted);
}
