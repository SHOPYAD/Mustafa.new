export function getDestinationPlacesList(destKey: string): ItineraryStopItem[] {
  const norm = destKey.toLowerCase().trim();
  if (/london|لندن/i.test(norm)) return LONDON_PLACES;
  if (/paris|باريس/i.test(norm)) return PARIS_PLACES;
  if (/istanbul|إسطنبول|اسطنبول/i.test(norm)) return ISTANBUL_PLACES;

  // Fallback to London or Paris if international
  if (/uk|britain|england|united kingdom/i.test(norm)) return LONDON_PLACES;
  if (/france|فرنس/i.test(norm)) return PARIS_PLACES;
  if (/turkey|تركيا/i.test(norm)) return ISTANBUL_PLACES;

  return LONDON_PLACES;
}

export function getAuthenticStopsForDay(
  dayPlan: any,
  dayIdx: number,
  destMeta: DestinationMetadata,
  isAr: boolean
): Array<{
  titleAr: string;
  titleEn: string;
  detailAr: string;
  detailEn: string;
  image: string;
  slotAr: string;
  slotEn: string;
  rating?: number;
  reviewsCount?: number;
  source?: string;
}> {
  // If the dayPlan already has authentic stops with non-generic images, use them
  if (Array.isArray(dayPlan?.stops) && dayPlan.stops.length >= 3) {
    const hasRealImages = dayPlan.stops.some(
      (s: any) => s.image && !s.image.includes("photo-1555396273")
    );
    if (hasRealImages) {
      return dayPlan.stops;
    }
  }

  const query = `${destMeta.cityEn} ${destMeta.cityAr} ${destMeta.destEn} ${destMeta.destAr}`;
  const catalog = getDestinationPlacesList(query);

  const total = catalog.length;
  const startIdx = (dayIdx * 3) % total;

  const stop1 = catalog[startIdx % total];
  const stop2 = catalog[(startIdx + 1) % total];
  const stop3 = catalog[(startIdx + 2) % total];

  return [stop1, stop2, stop3];
}
