const BY_ID = new Map<CatalogProviderId, CatalogProvider>(
  CATALOG.map((item) => [item.id, item])
);

export function listCatalogProviders(): readonly CatalogProvider[] {
  return CATALOG;
}

export function getCatalogProvider(id: CatalogProviderId): CatalogProvider {
  const found = BY_ID.get(id);
  if (!found) {
    throw new Error(`Unknown provider: ${id}`);
  }
  return found;
}

export function providersForVertical(vertical: ProviderVertical): CatalogProvider[] {
  return CATALOG.filter((item) => item.vertical === vertical);
}

export function providersByCategory(
  vertical: ProviderVertical,
  category: ProviderCategory
): CatalogProvider[] {
  return CATALOG.filter((item) => item.vertical === vertical && item.category === category);
}

export function defaultComingSoonEnabled(_id: CatalogProviderId): false {
  return false;
}

export function catalogIntegrity(): void {
  const seen = new Set<CatalogProviderId>();
  for (const item of CATALOG) {
    if (seen.has(item.id)) throw new Error(`Duplicate provider ${item.id}`);
    seen.add(item.id);
  }
  for (const id of PROVIDER_IDS) {
    if (!seen.has(id)) throw new Error(`Catalog missing ${id}`);
  }
}
