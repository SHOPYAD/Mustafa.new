export function expandClusterTerms(): Record<string, string[]> {
  const map: Record<string, string[]> = {};
  for (const cluster of RAW_THESAURUS_CLUSTERS) {
    const terms = cluster.baseTerms;
    for (const t of terms) {
      const normTerm = String(t)
        .replace(/[\u064B-\u0652]/g, "")
        .replace(/[أإآ]/g, "ا")
        .replace(/ة/g, "ه")
        .replace(/ى/g, "ي")
        .toLowerCase()
        .trim();
      if (normTerm.length < 2) continue;
      
      const targets = cluster.targetNodeIds;
      if (!map[normTerm]) map[normTerm] = [];
      map[normTerm] = Array.from(new Set([...map[normTerm], ...targets]));

      // Auto-expand with and without 'ال' for Arabic terms
      if (/[\u0600-\u06FF]/.test(normTerm)) {
        let alt = "";
        if (!normTerm.startsWith("ال") && normTerm.length > 2) alt = "ال" + normTerm;
        else if (normTerm.startsWith("ال") && normTerm.length > 4) alt = normTerm.slice(2);
        
        if (alt) {
          if (!map[alt]) map[alt] = [];
          map[alt] = Array.from(new Set([...map[alt], ...targets]));
        }

        // Prefixes
        for (const p of ["حجز ", "ارخص ", "اسعار ", "عروض ", "افضل ", "بحث "]) {
          const prefixed = (p + normTerm).trim();
          if (!map[prefixed]) map[prefixed] = [];
          map[prefixed] = Array.from(new Set([...map[prefixed], ...targets]));
        }
      }
    }
  }
  return map;
}

export const DOMAIN_THESAURUS_MAP: Record<string, string[]> = expandClusterTerms();

export function getThesaurusStats() {
  const total = Object.keys(DOMAIN_THESAURUS_MAP).length;
  return {
    totalTerms: total,
    totalClusters: THESAURUS_CLUSTERS.length,
    clusters: THESAURUS_CLUSTERS.map((c) => ({ id: c.id, domain: c.domain, terms: c.termsCount })),
  };
}
