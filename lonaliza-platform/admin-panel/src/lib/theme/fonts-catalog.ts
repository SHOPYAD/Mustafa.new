export const FONT_STORAGE_KEY = "lonaliza_admin_font";
export const DEFAULT_FONT_ID = "cairo";

export function getFontDefinition(fontId?: string): FontDefinition {
  if (!fontId) return FONTS_CATALOG[0];
  const found = FONTS_CATALOG.find((f) => f.id === fontId);
  return found || FONTS_CATALOG[0];
}

export function readStoredAdminFont(): string {
  if (typeof window === "undefined") return DEFAULT_FONT_ID;
  try {
    const stored = localStorage.getItem(FONT_STORAGE_KEY);
    if (stored && FONTS_CATALOG.some((f) => f.id === stored)) {
      return stored;
    }
  } catch {
    /* ignore */
  }
  return DEFAULT_FONT_ID;
}

export function persistAdminFont(fontId: string) {
  if (typeof window === "undefined") return;
  try {
    localStorage.setItem(FONT_STORAGE_KEY, fontId);
  } catch {
    /* ignore */
  }
}

/**
 * Dynamically loads Google Font stylesheet if not already present,
 * and sets CSS variable `--admin-font-family` on document root.
 */
export function applyAdminFont(fontId: string) {
  if (typeof document === "undefined") return;

  const font = getFontDefinition(fontId);
  const linkId = `google-font-${font.id}`;

  if (!document.getElementById(linkId)) {
    const link = document.createElement("link");
    link.id = linkId;
    link.rel = "stylesheet";
    link.href = `https://fonts.googleapis.com/css2?family=${font.googleFontFamily}&display=swap`;
    document.head.appendChild(link);
  }

  const root = document.documentElement;
  root.style.setProperty("--admin-font-family", font.cssFamily);
  root.dataset.adminFont = font.id;

  if (typeof window !== "undefined") {
    window.dispatchEvent(
      new CustomEvent("lonaliza:admin-font-change", { detail: { fontId, font } })
    );
  }
}
