/**
 * Returns localized city and airport name based on IATA code and place data.
 * Supports full localization across all site languages (AR, EN, TR, FR).
 */
export function getLocalizedPlace(
  iataOrCode?: string | null,
  fallbackName?: string | null,
  fallbackCity?: string | null,
  locale: string = "ar"
): { city: string; airport: string; name: string; code: string } {
  const rawCode = (iataOrCode || "").toUpperCase().trim();
  // Extract 3-letter IATA code if embedded like "LHR" or "LON (LHR)"
  const codeMatch = rawCode.match(/\b([A-Z]{3,4})\b/);
  const code = codeMatch ? codeMatch[1] : rawCode.slice(0, 4);

  const entry = AIRPORT_DICTIONARY[code];

  if (entry) {
    if (locale === "ar") {
      return { city: entry.cityAr, airport: entry.nameAr, name: entry.nameAr, code: entry.iata };
    }
    if (locale === "tr") {
      return { city: entry.cityTr, airport: entry.nameTr, name: entry.nameTr, code: entry.iata };
    }
    if (locale === "fr") {
      return { city: entry.cityFr, airport: entry.nameFr, name: entry.nameFr, code: entry.iata };
    }
    return { city: entry.cityEn, airport: entry.nameEn, name: entry.nameEn, code: entry.iata };
  }

  // Fallback cleanup
  let city = (fallbackCity || "").trim();
  let airport = (fallbackName || "").trim();

  // If city is just the IATA code or empty, try to derive from airport name
  if ((!city || city === code) && airport && airport !== code) {
    city = airport.replace(/\s*(?:Airport|International|Havalimanı|Aéroport|مطار|الدولي).*$/i, "").trim();
  }

  if (!city) city = code;
  if (!airport || airport === code) airport = city !== code ? `${city} (${code})` : code;

  // Localize standard airport tokens if in Arabic
  if (locale === "ar") {
    if (/airport/i.test(airport) && !/مطار/.test(airport)) {
      airport = airport.replace(/international airport/i, "الدولي").replace(/airport/i, "مطار").trim();
      if (!airport.startsWith("مطار")) airport = `مطار ${airport}`;
    }
  } else if (locale === "fr") {
    if (/airport/i.test(airport) && !/aéroport/i.test(airport)) {
      airport = airport.replace(/international airport/i, "international").replace(/airport/i, "").trim();
      airport = `Aéroport ${airport}`;
    }
  }

  return { city, airport, name: airport, code };
}
