/**
 * Helper to find any node or sub-module across all megaclusters
 */
export function findSovereignSubModule(idOrSlug: string): SubModuleNode | undefined {
  for (const cluster of SOVEREIGN_MEGACLUSTERS) {
    const found = cluster.subModules.find(m => m.id === idOrSlug || m.slug === idOrSlug);
    if (found) return found;
  }
  return undefined;
}

/**
 * Helper to find a cluster by ID or stationId
 */
export function findSovereignCluster(clusterIdOrStation: string): MegaclusterSector | undefined {
  return SOVEREIGN_MEGACLUSTERS.find(
    c => c.id === clusterIdOrStation || c.stationId === clusterIdOrStation
  );
}

