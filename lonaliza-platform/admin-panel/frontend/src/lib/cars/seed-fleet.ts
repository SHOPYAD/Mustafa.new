function extras(
  overrides: Partial<Record<CarExtra["key"], Partial<CarExtra>>> = {}
): CarExtra[] {
  return defaultCarExtras().map((extra) => ({
    ...extra,
    ...overrides[extra.key],
  }));
}

function car(partial: Omit<RentalCar, "currency" | "createdAt" | "updatedAt">): RentalCar {
  const now = "2026-01-01T00:00:00.000Z";
  return {
    ...partial,
    currency: "USD",
    createdAt: now,
    updatedAt: now,
  };
}

